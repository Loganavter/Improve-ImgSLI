#!/usr/bin/env python3
"""Validate cross-doc markdown links and cited repo paths; generate a backlink index.

Two corpora, deliberately kept apart:

* **Index corpus** — every ``*.md`` under ``docs/`` and
  ``src/tabs/<tab>/docs/`` (host docs + tab-owned docs). This is the set
  ``docs/dev/DOC_INDEX.md`` enumerates and computes backlinks for.
* **Agent-plane surfaces** — ``AGENTS.md``, ``skills/**/*.md``,
  ``.cursor/rules/**``, ``.github/**/*.md``. They are validated (relative
  links, anchors, cited repo paths) because agents execute them, but they are
  **not** in the index corpus: listing them there, or letting them contribute
  backlinks, would churn the generated index whenever an agent-plane file
  changed. ``DOC_INDEX.md`` stays a docs-only graph.

The script:

1. Parses every relative markdown link (``[text](path#anchor)``) in both
   corpora, resolves it against the linking file's directory, and reports any
   that don't point at a real file/dir on disk (a moved/renamed doc breaks
   this immediately instead of quietly). ``#anchor`` jumps are validated
   separately against the target file's headings (``broken_anchors``) —
   same-file ``#anchor`` links included. A link that resolves **outside** the
   repo root names a sibling checkout (``../sli-ui-toolkit/…`` or the private
   knowledge plane's directory) that a clean clone does not contain;
   it is not validated, because its absence says nothing about the link.
2. Validates backticked repo-root paths (``src/…``, ``tests/…``, ``docs/…``,
   ``scripts/…``, ``mcp-server/…``): the cited path must exist in this
   checkout. Illustrative forms are skipped by design (``…``/``...``,
   ``{a,b}``, ``<placeholder>``, globs, line numbers, ``$ `` transcripts), and
   so are dated records under ``**/investigations/`` (they name what was true
   when written) and paths that name a sibling repo. Findings are a ratchet
   against a committed baseline (``file<TAB>count``,
   ``src/devtools/docs_path_baseline.txt``, regenerate with
   ``--update-path-baseline``): pre-existing drift cannot be laundered, a NEW
   dead path fails, and a shrinking count passes. The cited-path machinery
   lives in ``docs_cited_paths.py`` (separate finding model, separate baseline);
   this module owns the corpus and the CLI.
3. Regenerates ``docs/dev/DOC_INDEX.md``: every doc in the index corpus,
   grouped by directory, each with a "Referenced by" backlink list computed
   from the link graph — so nobody hand-maintains which docs point at which.

Usage:
    python src/devtools/docs_link_graph.py            # report
    python src/devtools/docs_link_graph.py --json
    python src/devtools/docs_link_graph.py --strict    # exit 1 on broken links/anchors/paths
    python src/devtools/docs_link_graph.py --write-index   # regenerate DOC_INDEX.md
    python src/devtools/docs_link_graph.py --update-path-baseline
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

REPO_ROOT = Path(__file__).resolve().parents[2]
SRC_ROOT = REPO_ROOT / "src"
if str(SRC_ROOT) not in sys.path:
    sys.path.insert(0, str(SRC_ROOT))

from devtools.docs_cited_paths import (  # noqa: E402  — stdlib-only sibling, no app import
    PATH_BASELINE_REL,
    MissingRepoPath,
    collect_missing_repo_paths,
    load_path_baseline,
    path_regressions,
    render_baseline,
)

_LINK_RE = re.compile(r"\[([^\]]*)\]\(([^)]+)\)")
_INDEX_REL_PATH = "docs/dev/DOC_INDEX.md"
_GENERATED_MARKER = "<!-- AUTO-GENERATED by src/devtools/docs_link_graph.py — do not hand-edit -->"

#: Agent-plane markdown surfaces outside the index corpus (see module docstring).
_EXTRA_SOURCE_GLOBS = (
    "AGENTS.md",
    "skills/**/*.md",
    ".cursor/rules/**/*",
    ".github/**/*.md",
)


@dataclass(frozen=True, slots=True)
class BrokenLink:
    source: str  # repo-relative path of the file containing the link
    line: int
    text: str
    target: str  # raw link target as written


@dataclass(frozen=True, slots=True)
class DocsLinkReport:
    docs: tuple[str, ...]  # repo-relative paths, sorted (index corpus only)
    broken: tuple[BrokenLink, ...]
    backlinks: dict[str, tuple[str, ...]]  # doc -> sorted docs that link to it
    # Anchor drift (``path#missing-heading`` / ``#missing-heading``) is
    # tracked separately from ``broken``: a moved file breaks the whole
    # reference, a renamed heading only the jump. ``--strict`` fails on
    # either; the ``test_real_repo_has_no_broken_doc_links`` dogma pins
    # only ``broken`` (file-level), so anchor cleanup can land incrementally.
    broken_anchors: tuple[BrokenLink, ...] = ()
    #: Every file that was scanned for links (index corpus + agent-plane
    #: surfaces). ``docs`` stays the index corpus so the generated index is
    #: unaffected by agent-plane files.
    link_sources: tuple[str, ...] = ()
    #: Cited repo-root paths that do not exist (unfiltered by the baseline —
    #: ``path_regressions`` applies it).
    missing_paths: tuple[MissingRepoPath, ...] = ()


def default_repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def discover_doc_files(repo_root: Path) -> list[Path]:
    """Every ``*.md`` under ``docs/`` and each tab's ``docs/`` package."""
    out: list[Path] = []
    docs_root = repo_root / "docs"
    if docs_root.is_dir():
        out.extend(sorted(docs_root.rglob("*.md")))
    tabs_root = repo_root / "src" / "tabs"
    if tabs_root.is_dir():
        for tab_docs in sorted(tabs_root.glob("*/docs")):
            if tab_docs.is_dir():
                out.extend(sorted(tab_docs.rglob("*.md")))
    return [p for p in out if "__pycache__" not in p.parts]


def discover_extra_source_files(repo_root: Path) -> list[Path]:
    """Agent-plane markdown surfaces (``AGENTS.md``, ``skills/``, ``.cursor``, ``.github``).

    Validated for links and cited paths, but never listed in the generated
    index nor contributing backlinks (see the module docstring).
    """
    out: list[Path] = []
    for pattern in _EXTRA_SOURCE_GLOBS:
        out.extend(p for p in sorted(repo_root.glob(pattern)) if p.is_file())
    return [p for p in out if "__pycache__" not in p.parts]


def discover_link_sources(repo_root: Path) -> list[Path]:
    """Every file scanned for links/cited paths: index corpus + agent-plane."""
    sources = discover_doc_files(repo_root) + discover_extra_source_files(repo_root)
    return sorted(set(sources), key=lambda p: p.as_posix())



def _heading_slugs(text: str) -> set[str]:
    """GitHub-style heading anchors present in a markdown document.

    ``## Foo Bar`` → ``foo-bar`` (lowercase, punctuation dropped,
    whitespace runs collapsed to one hyphen). Fenced code blocks are not
    headings. Best-effort: custom ``{#anchor}`` suffixes are not parsed.
    """
    slugs: set[str] = set()
    in_fence = False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        match = re.match(r"#{1,6}\s+(.*)", stripped)
        if not match:
            continue
        heading = re.sub(r"`([^`]*)`", r"\1", match.group(1)).strip().lower()
        heading = re.sub(r"[^\w\s-]", "", heading)
        slug = re.sub(r"\s+", "-", heading).strip("-")
        if slug:
            slugs.add(slug)
    return slugs


def _split_anchor(target: str) -> tuple[str, str]:
    """Split a raw link target into ``(path_part, anchor)`` (either may be empty)."""
    if "#" not in target:
        return target, ""
    path_part, anchor = target.split("#", 1)
    return path_part, anchor


def _rel(path: Path, *, repo_root: Path) -> str:
    try:
        return path.relative_to(repo_root).as_posix()
    except ValueError:
        return path.as_posix()


def _is_external(target: str) -> bool:
    return bool(re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", target)) or target.startswith("//")


def _resolve_link(target: str, *, doc_path: Path, repo_root: Path) -> Path | None:
    """Resolve a relative link target to an absolute path, stripping any anchor.

    Returns None for links this checker doesn't validate (external URLs,
    pure same-file anchors, mailto:, etc).
    """
    target = target.strip()
    if not target or _is_external(target) or target.startswith("mailto:"):
        return None
    if target.startswith("#"):
        return None  # same-file anchor
    path_part = target.split("#", 1)[0]
    if not path_part:
        return None
    if path_part.startswith("/"):
        resolved = repo_root / path_part.lstrip("/")
    else:
        resolved = (doc_path.parent / path_part).resolve()
    return resolved


def _is_within(path: Path, root: Path) -> bool:
    """Whether ``path`` stays inside ``root`` after resolving symlinks/``..``."""
    try:
        path.resolve().relative_to(root.resolve())
    except (OSError, ValueError):
        return False
    return True


def analyze_docs(*, repo_root: Path | None = None) -> DocsLinkReport:
    root = repo_root if repo_root is not None else default_repo_root()
    doc_paths = discover_doc_files(root)
    doc_rels = {_rel(p, repo_root=root) for p in doc_paths}
    link_sources = discover_link_sources(root)

    broken: list[BrokenLink] = []
    broken_anchors: list[BrokenLink] = []
    backlinks: dict[str, set[str]] = {rel: set() for rel in doc_rels}
    # Cache heading slugs per doc so each target file is scanned once.
    slug_cache: dict[str, set[str]] = {}

    def _slugs_of(doc_rel: str) -> set[str]:
        if doc_rel not in slug_cache:
            try:
                slug_cache[doc_rel] = _heading_slugs(
                    (root / doc_rel).read_text(encoding="utf-8")
                )
            except OSError:
                slug_cache[doc_rel] = set()
        return slug_cache[doc_rel]

    for doc_path in link_sources:
        source_rel = _rel(doc_path, repo_root=root)
        text = doc_path.read_text(encoding="utf-8")
        in_fence = False
        for lineno, line in enumerate(text.splitlines(), start=1):
            if line.lstrip().startswith("```"):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            for match in _LINK_RE.finditer(line):
                link_text, target = match.group(1), match.group(2)
                path_part, anchor = _split_anchor(target.strip())
                if not path_part:
                    # Same-file anchor (``#heading``): validate the jump.
                    if anchor and anchor not in _slugs_of(source_rel):
                        broken_anchors.append(
                            BrokenLink(source=source_rel, line=lineno, text=link_text, target=target)
                        )
                    continue
                resolved = _resolve_link(target, doc_path=doc_path, repo_root=root)
                if resolved is None:
                    continue
                if not _is_within(resolved, root):
                    # A sibling checkout (``../sli-ui-toolkit/…``) is absent from
                    # a clean clone; its absence says nothing about the link.
                    continue
                if not resolved.exists():
                    broken.append(
                        BrokenLink(source=source_rel, line=lineno, text=link_text, target=target)
                    )
                    continue
                if anchor:
                    target_rel = _rel(resolved, repo_root=root)
                    if target_rel in doc_rels and anchor not in _slugs_of(target_rel):
                        broken_anchors.append(
                            BrokenLink(source=source_rel, line=lineno, text=link_text, target=target)
                        )
                target_rel = _rel(resolved, repo_root=root)
                # DOC_INDEX.md is generated and links every doc by
                # construction, so its own links would add meaningless
                # self-referential backlinks to every entry — and make the
                # generated index a moving target (a one-pass --write-index
                # can never include its own backlinks, so the file would
                # always be "stale" against a re-analysis). Exclude it from
                # contributing backlinks so the output is a fixed point.
                # Agent-plane sources (``AGENTS.md``, ``skills/``) are excluded
                # for the same fixed-point reason plus scope: the index is a
                # docs-only graph.
                if (
                    target_rel in doc_rels
                    and target_rel != source_rel
                    and source_rel != _INDEX_REL_PATH
                    and source_rel in doc_rels
                ):
                    backlinks[target_rel].add(source_rel)

    return DocsLinkReport(
        docs=tuple(sorted(doc_rels)),
        broken=tuple(broken),
        backlinks={k: tuple(sorted(v)) for k, v in backlinks.items()},
        broken_anchors=tuple(broken_anchors),
        link_sources=tuple(_rel(p, repo_root=root) for p in link_sources),
        missing_paths=collect_missing_repo_paths(link_sources, root),
    )



def _doc_title(doc_rel: str, *, repo_root: Path) -> str:
    path = repo_root / doc_rel
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            stripped = line.strip()
            if stripped.startswith("# "):
                return stripped[2:].strip()
    except OSError:
        pass
    return Path(doc_rel).stem


def render_index(report: DocsLinkReport, *, repo_root: Path | None = None) -> str:
    root = repo_root if repo_root is not None else default_repo_root()
    lines: list[str] = [
        "# Doc Index",
        "",
        _GENERATED_MARKER,
        "",
        "Every doc under `docs/` and `src/tabs/<tab>/docs/`, grouped by",
        "directory, with auto-computed backlinks (who links to this doc).",
        "Regenerate: `python src/devtools/docs_link_graph.py --write-index`.",
        "Checked by `tests/devtools/test_docs_link_graph.py`.",
        "",
    ]

    by_dir: dict[str, list[str]] = {}
    for doc_rel in report.docs:
        by_dir.setdefault(str(Path(doc_rel).parent), []).append(doc_rel)

    for directory in sorted(by_dir):
        lines.append(f"## {directory}/")
        lines.append("")
        for doc_rel in sorted(by_dir[directory]):
            title = _doc_title(doc_rel, repo_root=root)
            index_dir = Path(_INDEX_REL_PATH).parent
            rel_from_index = _relpath(doc_rel, from_dir=str(index_dir))
            lines.append(f"- **[{title}]({rel_from_index})** — `{doc_rel}`")
            refs = report.backlinks.get(doc_rel, ())
            if refs:
                ref_links = ", ".join(
                    f"[{r}]({_relpath(r, from_dir=str(index_dir))})" for r in refs
                )
                lines.append(f"  Referenced by: {ref_links}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def _relpath(target_rel: str, *, from_dir: str) -> str:
    import os

    return os.path.relpath(target_rel, start=from_dir).replace("\\", "/")


def _print_report(report: DocsLinkReport, *, regressions: tuple[MissingRepoPath, ...] = ()) -> int:
    print(f"Docs scanned: {len(report.docs)}")
    print(f"Link sources scanned: {len(report.link_sources)}")
    print(f"Broken links: {len(report.broken)}")
    if report.broken:
        print()
        print("Broken links:")
        for b in report.broken:
            print(f"  - {b.source}:{b.line} [{b.text}]({b.target})")
    print(f"Broken anchors: {len(report.broken_anchors)}")
    if report.broken_anchors:
        print()
        print("Broken anchors (file exists, #heading missing):")
        for b in report.broken_anchors:
            print(f"  - {b.source}:{b.line} [{b.text}]({b.target})")
    print(f"Missing repo-root paths: {len(report.missing_paths)} (baseline regressions: {len(regressions)})")
    if regressions:
        print()
        print("New missing repo-root paths (baseline grew; fix the citation):")
        for m in regressions:
            print(f"  - {m.source}:{m.line} `{m.token}`")
    return len(report.broken) + len(report.broken_anchors) + len(regressions)


def _resolve_path_baseline(args, root: Path) -> Path | None:
    """Explicit ``--path-baseline``, else the committed default when present."""
    if args.path_baseline is not None:
        return args.path_baseline
    candidate = root / PATH_BASELINE_REL
    return candidate if candidate.is_file() else None


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=default_repo_root())
    parser.add_argument("--json", action="store_true")
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Exit 1 on any broken link/anchor or baseline path regression.",
    )
    parser.add_argument(
        "--write-index",
        action="store_true",
        help="Regenerate docs/dev/DOC_INDEX.md in place.",
    )
    parser.add_argument(
        "--path-baseline",
        type=Path,
        default=None,
        help=(
            "accepted cited-path findings (file<TAB>count); default: the "
            f"committed {PATH_BASELINE_REL} when present"
        ),
    )
    parser.add_argument(
        "--update-path-baseline",
        action="store_true",
        help=f"Rewrite {PATH_BASELINE_REL} from the current findings.",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    report = analyze_docs(repo_root=args.repo_root)

    if args.write_index:
        content = render_index(report, repo_root=args.repo_root)
        (args.repo_root / _INDEX_REL_PATH).write_text(content, encoding="utf-8")
        print(f"Wrote {_INDEX_REL_PATH}")
        # DOC_INDEX.md itself is part of the scanned corpus, so writing it
        # can change the link/backlink graph — recompute before reporting.
        report = analyze_docs(repo_root=args.repo_root)

    baseline_path = _resolve_path_baseline(args, args.repo_root)
    if args.update_path_baseline:
        target = baseline_path or (args.repo_root / PATH_BASELINE_REL)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_baseline(report.missing_paths), encoding="utf-8")
        print(f"Wrote {target}")
        baseline_path = target

    baseline = load_path_baseline(baseline_path) if baseline_path is not None else {}
    regressions = path_regressions(report.missing_paths, baseline)

    if args.json:
        import json

        payload = {
            "docs": list(report.docs),
            "link_sources": list(report.link_sources),
            "broken": [
                {"source": b.source, "line": b.line, "text": b.text, "target": b.target}
                for b in report.broken
            ],
            "broken_anchors": [
                {"source": b.source, "line": b.line, "text": b.text, "target": b.target}
                for b in report.broken_anchors
            ],
            "missing_paths": [
                {"source": m.source, "line": m.line, "token": m.token}
                for m in report.missing_paths
            ],
            "path_regressions": [
                {"source": m.source, "line": m.line, "token": m.token}
                for m in regressions
            ],
        }
        print(json.dumps(payload, ensure_ascii=False, indent=2))
    else:
        _print_report(report, regressions=regressions)

    if args.strict and (report.broken or report.broken_anchors or regressions):
        return 1
    return 0



if __name__ == "__main__":
    raise SystemExit(main())
